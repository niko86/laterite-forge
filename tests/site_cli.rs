/// Properties are required on every unit, and groundwater on the site: a
/// preset without them exits 5 naming the field.
#[test]
fn a_preset_without_properties_or_groundwater_exits_5_naming_the_field() {
    let dir = tempfile::tempdir().unwrap();
    let water = "groundwater_depth_m = { min = 1.0, max = 4.0, basis = \"test fixture\" }\n";
    assert!(PRESET.contains(water));
    let no_water = preset(dir.path(), &PRESET.replacen(water, "", 1));
    let out = gen_site(dir.path(), &no_water, &[]);
    assert_eq!(out.status.code(), Some(5), "{}", stderr(&out));
    assert!(
        stderr(&out).contains("site.groundwater_depth_m: missing"),
        "{}",
        stderr(&out)
    );

    // Every `[units.properties]` table runs to the next blank line.
    let mut bare = String::new();
    let mut skipping = false;
    for line in PRESET.lines() {
        if line == "[units.properties]" {
            skipping = true;
        } else if line.is_empty() {
            skipping = false;
        }
        if !skipping {
            bare.push_str(line);
            bare.push('\n');
        }
    }
    let no_props = preset(dir.path(), &bare);
    let out = gen_site(dir.path(), &no_props, &[]);
    assert_eq!(out.status.code(), Some(5), "{}", stderr(&out));
    let err = stderr(&out);
    assert!(err.contains("units[0] (TOP).properties: missing"), "{err}");
    assert!(err.contains("units[1] (BASE).properties: missing"), "{err}");
}

const STRENGTH: &str = r#"strength = { relation = "cu.linear_with_depth", cu_top_kpa = { min = 60, max = 120, basis = "test fixture" }, per_m = { min = 4, max = 8, basis = "test fixture" } }
spt = { relation = "spt.stroud_butler", f1 = { min = 4, max = 6, basis = "test fixture" } }
"#;

/// `PRESET` (its last unit, BASE, takes `props`) with a suite on top.
fn with_strength(props: &str, suite: &str) -> String {
    format!("{PRESET}{props}{suite}")
}

/// An unknown relation, a missing parameter, a missing basis, and a suite
/// heading the unit's relations cannot make all exit 5 naming the field, the
/// suite entry and the unit.
#[test]
fn strength_and_spt_problems_exit_5_naming_the_field() {
    let dir = tempfile::tempdir().unwrap();
    let trit = "\n[[suite]]\ngroup = \"TRIG\"\nheadings = []\nunits = [\"BASE\"]\nrate = { min = 1, max = 1, basis = \"test fixture\" }\n\n[[suite]]\ngroup = \"TRIT\"\nheadings = [\"TRIT_CU\"]\n";
    let ispt = "\n[[suite]]\ngroup = \"ISPT\"\nheadings = [\"ISPT_NVAL\"]\nunits = [\"BASE\"]\nrate = { min = 1, max = 1, basis = \"test fixture\" }\n";
    let llpl = "\n[[suite]]\ngroup = \"LLPL\"\nheadings = [\"LLPL_LL\"]\nunits = [\"TOP\"]\nrate = { min = 1, max = 1, basis = \"test fixture\" }\n";
    let cases = [
        (
            String::new(),
            llpl,
            "suite[0].headings[0]: LLPL_LL needs fine properties (liquid and plastic limits), but unit \"TOP\" has none",
        ),
        (
            STRENGTH.replace("cu.linear_with_depth", "cu.ocr"),
            "",
            "units[1] (BASE).properties.strength.relation",
        ),
        (
            STRENGTH.replace(
                ", per_m = { min = 4, max = 8, basis = \"test fixture\" }",
                "",
            ),
            "",
            "units[1] (BASE).properties.strength.per_m: missing",
        ),
        (
            STRENGTH.replace("max = 120, basis = \"test fixture\"", "max = 120"),
            "",
            "units[1] (BASE).properties.strength.cu_top_kpa: no basis",
        ),
        (
            String::new(),
            trit,
            "suite[1].headings[0]: TRIT_CU needs undrained strength, but unit \"BASE\"",
        ),
        (
            String::new(),
            ispt,
            "suite[0].headings[0]: ISPT_NVAL needs strength and spt (a fine unit), but unit \"BASE\"",
        ),
    ];
    for (props, suite, expected) in cases {
        let p = preset(dir.path(), &with_strength(&props, suite));
        let out = gen_site(dir.path(), &p, &[]);
        assert_eq!(out.status.code(), Some(5), "{expected}: {}", stderr(&out));
        assert!(
            stderr(&out).contains(expected),
            "{expected}: {}",
            stderr(&out)
        );
    }
}

/// A generated tyneside-till file, with its TREG and TRET groups, passes dual
/// validation: Rust and python-ags4 both find nothing (#68). Without the
/// oracle the test skips, or under `FORGE_REQUIRE_ORACLE=1` fails.
#[test]
fn a_tyneside_till_file_with_effective_stress_triaxial_agrees_with_python_ags4() {
    let dir = tempfile::tempdir().unwrap();
    for seed in ["1", "4", "9"] {
        let out = dir.path().join(format!("out{seed}"));
        let made = forge(&[
            "gen",
            "--site",
            "tyneside-till",
            "--seed",
            seed,
            "--json",
            "--out-dir",
            out.to_str().unwrap(),
        ]);
        assert_eq!(made.status.code(), Some(0), "{}", stderr(&made));
        let doc: serde_json::Value = serde_json::from_slice(&made.stdout).unwrap();
        let path = doc["candidates"][0]["path"].as_str().unwrap().to_string();
        let text = std::fs::read_to_string(&path).unwrap();
        assert!(
            text.contains("\"GROUP\",\"TREG\"") && text.contains("\"GROUP\",\"TRET\""),
            "seed {seed} has no TREG and TRET"
        );
        let checked = forge(&["check", &path, "--json"]);
        let verdict: serde_json::Value = serde_json::from_slice(&checked.stdout).unwrap();
        if verdict["oracle"] == false {
            assert!(
                std::env::var_os("FORGE_REQUIRE_ORACLE").is_none(),
                "FORGE_REQUIRE_ORACLE is set but there is no oracle: {}",
                stderr(&checked)
            );
            eprintln!(
                "SKIP tyneside-till dual validation: {}",
                stderr(&checked).trim()
            );
            return;
        }
        assert_eq!(checked.status.code(), Some(0), "seed {seed}: {verdict}");
        assert_eq!(verdict["verdict"], "AGREE", "seed {seed}: {verdict}");
        assert_eq!(verdict["rust_rules"], serde_json::json!([]), "seed {seed}");
        assert_eq!(
            verdict["python_rules"],
            serde_json::json!([]),
            "seed {seed}"
        );
    }
}
