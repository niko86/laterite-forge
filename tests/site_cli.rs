//! `gen --site` through the real binary (#21): the flag's contract, not the
//! ground it generates (the site layer's own tests hold that).

use std::path::Path;
use std::process::{Command, Output};

/// Two units, the minimum a preset can be: one with a thickness, then the
/// last, which runs to final depth.
const PRESET: &str = r#"
schema = 1
name = "cli-basin"
version = 1
summary = "A fixture."

[site]
extent_m = { x = 200.0, y = 100.0 }
ground_level_m = { min = 10.0, max = 12.0, basis = "test fixture" }
groundwater_depth_m = { min = 1.0, max = 4.0, basis = "test fixture" }

[[hole_types]]
code = "CP"
weight = 1
final_depth_m = { min = 10.0, max = 20.0, basis = "test fixture" }

[[units]]
id = "TOP"
name = "Top"
thickness_m = { min = 1.0, max = 3.0, basis = "test fixture" }
description = { principals = ["SAND"], secondaries = [], colours = ["brown"] }
sampling = { types = ["B"], interval_m = { min = 1.0, max = 1.5, basis = "test fixture" } }

[units.properties]
spt_n = { min = 10, max = 30, basis = "test fixture" }
moisture_content_percent = { min = 8, max = 15, basis = "test fixture" }
particle_density_ratio = { min = 2.6, max = 2.7, basis = "test fixture" }

[[units]]
id = "BASE"
name = "Base"
description = { principals = ["CLAY"], secondaries = [], colours = ["grey"] }
sampling = { types = ["U"], interval_m = { min = 1.5, max = 3.0, basis = "test fixture" } }

[units.properties]
plastic_limit_percent = { min = 20, max = 30, basis = "test fixture" }
plasticity_index_percent = { min = 30, max = 50, basis = "test fixture" }
liquidity_index = { min = 0.0, max = 0.3, basis = "test fixture" }
particle_density_ratio = { min = 2.6, max = 2.7, basis = "test fixture" }
"#;

fn forge(args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_laterite-ags4-forge"))
        .args(args)
        .output()
        .expect("the binary runs")
}

fn preset(dir: &Path, text: &str) -> String {
    let path = dir.join("preset.toml");
    std::fs::write(&path, text).unwrap();
    path.to_str().unwrap().to_string()
}

fn gen_site(dir: &Path, preset: &str, extra: &[&str]) -> Output {
    let out = dir.join("out");
    let mut args = vec!["gen", "--site", preset, "--json", "--out-dir"];
    args.push(out.to_str().unwrap());
    args.extend_from_slice(extra);
    forge(&args)
}

fn stderr(out: &Output) -> String {
    String::from_utf8_lossy(&out.stderr).into_owned()
}

/// A preset makes a clean candidate, reported under the preset's name.
#[test]
fn gen_site_writes_a_clean_candidate() {
    let dir = tempfile::tempdir().unwrap();
    let p = preset(dir.path(), PRESET);
    let out = gen_site(dir.path(), &p, &[]);
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
    let doc: serde_json::Value = serde_json::from_slice(&out.stdout).unwrap();
    assert_eq!(doc["scaffold"], "site:cli-basin");
    let cand = &doc["candidates"][0];
    assert_eq!(cand["rust_rules"], serde_json::json!([]), "{cand}");
    let text = std::fs::read_to_string(cand["path"].as_str().unwrap()).unwrap();
    assert!(
        text.contains("SYNTHETIC: generated by laterite-ags4-forge from site preset cli-basin v1")
    );
}

