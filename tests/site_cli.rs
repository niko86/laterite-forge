/// `--site`, `--grid` and `--origin` are documented in `gen --help` (ADR 0001,
/// from london-basin v3), and `--readme` covers the site model.
#[test]
fn site_is_documented_in_help() {
    let out = forge(&["gen", "--help"]);
    assert_eq!(out.status.code(), Some(0));
    let help = String::from_utf8_lossy(&out.stdout);
    for flag in [
        "--site <PRESET>",
        "--grid",
        "--origin <E,N>",
        "london-basin",
        "tyneside-till",
    ] {
        assert!(help.contains(flag), "{flag} is missing from gen --help");
    }
    let out = forge(&["--readme"]);
    assert_eq!(out.status.code(), Some(0));
    let readme = String::from_utf8_lossy(&out.stdout);
    for text in [
        "## Site model",
        "--site london-basin",
        "--site tyneside-till",
        "--grid bng --origin",
        "SYNTHETIC",
    ] {
        assert!(readme.contains(text), "{text} is missing from --readme");
    }
}

#[test]
fn grid_needs_an_origin_and_an_origin_needs_a_grid() {
    let dir = tempfile::tempdir().unwrap();
    let p = preset(dir.path(), PRESET);
    for extra in [&["--grid", "bng"][..], &["--origin", "530000,180000"][..]] {
        let out = gen_site(dir.path(), &p, extra);
        assert_eq!(out.status.code(), Some(5), "{extra:?}: {}", stderr(&out));
    }
    let out = gen_site(dir.path(), &p, &["--grid", "bng", "--origin", "east,north"]);
    assert_eq!(out.status.code(), Some(5), "{}", stderr(&out));
    assert!(stderr(&out).contains("--origin"), "{}", stderr(&out));
}

